/**
 * Generate the static model schemas from ArkType without linking its runtime into core/lite.
 *
 * @module
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { createModelJsonSchemas } from "../packages/core/src/schema.ts";

const target = fileURLToPath(
  new URL("../packages/core/src/generated/model-schema.ts", import.meta.url),
);
const schemas = createModelJsonSchemas();
const source = `// Generated by scripts/sync-model-schema.ts. Don't edit by hand.

/** JSON Schema (draft-07) for a single documentation record. */
export const cssDocEntrySchema: Readonly<Record<string, unknown>> = ${JSON.stringify(schemas.entry, null, 2)};

/** JSON Schema (draft-07) for the whole documentation model. */
export const cssDocSchema: Readonly<Record<string, unknown>> = ${JSON.stringify(
  { ...schemas.model, $id: "https://cssdoc.dev/model.schema.json" },
  null,
  2,
)};
`;

if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
    console.error("Model JSON Schema is out of sync — run `vp run @cssdoc/core#sync:model-schema`");
    process.exitCode = 1;
  }
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, source);
}
