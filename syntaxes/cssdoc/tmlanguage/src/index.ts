/**
 * `@cssdoc/tmlanguage` — a TextMate injection grammar that highlights cssdoc doc-comment tags inside
 * CSS comments, the way TSDoc highlights JSDoc tags inside `/** … *\/` comments. It layers onto the host
 * CSS grammar's comment scope, so `@component`, `@modifier`, `@cssproperty`, `{@link …}`, the release
 * metadata tags, and custom properties light up wherever CSS is highlighted.
 *
 * The grammar is built from the canonical tag vocabulary in `@cssdoc/spec` via
 * {@link buildInjectionGrammar}, so the tag list is defined exactly once. The default export is the
 * grammar as a Shiki `LanguageRegistration` (it carries `injectTo`), so it drops into a Shiki or
 * VitePress config; the same grammar is also published as `./cssdoc.injection.tmLanguage.json`
 * (generated by `scripts/generate.mjs`, kept in sync by the tests) for VS Code's
 * `contributes.grammars` and other TextMate hosts.
 *
 * Uses tier-organized regex patterns from `@cssdoc/regex` for consistency and maintainability.
 *
 * @example
 * ```ts
 * // .vitepress/config.ts
 * import cssdoc from "@cssdoc/tmlanguage";
 * export default { markdown: { languages: [cssdoc] } };
 * ```
 *
 * @module \@cssdoc/tmlanguage
 */

import {
  ALPHA,
  ALPHANUMERIC_EXTENDED,
  AT,
  ASTERISK,
  BACKTICK_CHAR,
  BRACE_OPEN,
  BRACE_OPEN_CHAR,
  BRACE_CLOSE,
  BRACE_CLOSE_CHAR,
  COLON,
  DIGIT,
  DOT,
  DOUBLE_DASH,
  PAREN_CLOSE,
  PAREN_OPEN,
  PIPE_CHAR,
  PIPE,
  SPACE_TAB,
  WORD_BOUNDARY,
  CSSDOC_STRUCTURE_TAG,
  TOKEN_CLASS_SELECTOR,
  CSSDOC_COMPONENT_REF,
  CSSDOC_DIRECTIVE_KIND,
  COMMENT_END,
  TILDE_CHAR,
} from "@cssdoc/regex";
import { CSSDOC_TAGS, cssdocTagNamesByArgument, cssdocTagNamesByKind } from "@cssdoc/spec";

/** A TextMate capture assignment (`{ "1": { name } }`). */
type Captures = Record<string, { name: string }>;

/** A TextMate pattern rule — a match rule, a begin/end rule, or a `#repository` reference. */
interface TmRule {
  name?: string;
  match?: string;
  begin?: string;
  end?: string;
  beginCaptures?: Captures;
  endCaptures?: Captures;
  captures?: Captures;
  patterns?: TmRule[];
  include?: string;
}

/** A TextMate injection grammar. */
export interface InjectionGrammar {
  /** TextMate grammar schema URL. */
  $schema: string;
  /** Human-readable grammar name. */
  name: string;
  /** Scope assigned to the injection grammar. */
  scopeName: string;
  /** Host scopes into which this grammar injects its patterns. */
  injectionSelector: string;
  /** Top-level TextMate patterns. */
  patterns: TmRule[];
  /** Named rules referenced by the patterns. */
  repository: Record<string, TmRule>;
}

/** A Shiki/VS Code registration: grammar + inject targets. */
export interface InjectionLanguageRegistration extends InjectionGrammar {
  /** Host language scopes to register as injection targets. */
  injectTo: string[];
}

const TAG_SCOPE = "storage.type.class.cssdoc";
const alt = (names: readonly string[]): string => names.join("|");

/**
 * Create a tag alternation pattern for TextMate grammar.
 * Produces a pattern like `@(?:component|variant|...)` from a list of tag names.
 */
const createTagAlternation = (tags: readonly string[]): string => `@(?:${alt(tags)})`;

// Pattern builders for TextMate grammar (simple patterns from Tier 0/1 character classes)
const buildIdentifier = (): string => `${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*`;
const buildQualifiedIdentifier = (): string =>
  `${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*(?:${DOT.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*)*`;
const buildModifierName = (): string => `-?${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*`;
const buildClassSelector = (): string =>
  `${DOT.source}?${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*`;
const buildCustomProperty = (): string =>
  `${DOUBLE_DASH.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*`;
const buildStateValue = (): string =>
  `${COLON.source}?${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*(?:${PAREN_OPEN.source}${ALPHANUMERIC_EXTENDED.source}*${PAREN_CLOSE.source})?`;

/**
 * Build the cssdoc injection grammar from the canonical `@cssdoc/spec` vocabulary. The argument-bearing
 * tags (`@modifier`, `@part`/`@slot`, `@cssproperty`) get their own rules that also colour the token
 * that follows; the inline tags open a `{@link …}` rule; every other tag is a bare keyword.
 */
export function buildInjectionGrammar(): InjectionGrammar {
  const recordTags = alt(cssdocTagNamesByKind("record"));
  const modifierTags = alt(cssdocTagNamesByArgument("modifier-name"));
  const partTags = alt([...cssdocTagNamesByArgument("part-name"), "selector", "pseudo"]);
  const propertyTags = alt(cssdocTagNamesByArgument("custom-property"));
  // Everything argument-less that isn't a record tag or `@cssstate` — those get their own value-colouring
  // rules below (a record's name, a state's `:state(…)`), so they must not fall through to the bare
  // keyword rule. Also exclude selector/pseudo which are handled in part-tag.
  const blockTags = alt(
    CSSDOC_TAGS.filter(
      (t) =>
        t.kind !== "inline" &&
        t.kind !== "record" &&
        t.name !== "cssstate" &&
        !t.argument &&
        t.name !== "selector" &&
        t.name !== "pseudo",
    ).map((t) => t.name),
  );
  const fencePrefix = `(?:${SPACE_TAB.source}*${ASTERISK.source}${SPACE_TAB.source}?)?${SPACE_TAB.source}{0,3}`;
  const fenceRule = (marker: string): TmRule => ({
    name: "markup.fenced_code.block.cssdoc",
    begin: `^(?!.*${COMMENT_END.source})${fencePrefix}(${marker}{3,})${marker === BACKTICK_CHAR ? `[^${BACKTICK_CHAR}]*` : ".*"}$`,
    end: `^${fencePrefix}\\1${marker}*${SPACE_TAB.source}*$|(?=${COMMENT_END.source})`,
  });

  return {
    $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    name: "cssdoc",
    scopeName: "text.cssdoc",
    injectionSelector:
      "L:comment.block.css - markup.fenced_code.block.cssdoc, L:comment.block.scss - markup.fenced_code.block.cssdoc, L:comment.block.less - markup.fenced_code.block.cssdoc",
    patterns: [
      { include: "#directive-comment" },
      { include: "#backtick-fence" },
      { include: "#tilde-fence" },
      { include: "#inline-tag" },
      { include: "#record-tag" },
      { include: "#modifier-tag" },
      { include: "#part-tag" },
      { include: "#property-tag" },
      { include: "#ref-tag" },
      { include: "#member-tag" },
      { include: "#state-tag" },
      { include: "#structure-tag" },
      { include: "#block-tag" },
      { include: "#custom-property" },
    ],
    repository: {
      "backtick-fence": fenceRule(BACKTICK_CHAR),
      "tilde-fence": fenceRule(TILDE_CHAR),
      "directive-comment": {
        begin: `(?<=/\\*)[ \\t]*(?=cssdoc-${CSSDOC_DIRECTIVE_KIND.source}|$)`,
        end: `(?=\\*/)|(?=\\S)(?!cssdoc-${CSSDOC_DIRECTIVE_KIND.source})`,
        patterns: [
          {
            begin: `(cssdoc-${CSSDOC_DIRECTIVE_KIND.source})`,
            beginCaptures: { "1": { name: "keyword.control.directive.cssdoc" } },
            end: `(?=\\*/)|(?=\\s-\\s)|(?=^-\\s)`,
            patterns: [{ match: String.raw`[^\s,*/]+`, name: "entity.name.tag.rule.cssdoc" }],
          },
        ],
      },
      "inline-tag": {
        name: "meta.inline-tag.cssdoc",
        begin: `(${BRACE_OPEN.source})(${createTagAlternation(cssdocTagNamesByKind("inline"))})${WORD_BOUNDARY.source}`,
        beginCaptures: {
          "1": { name: "punctuation.definition.tag.begin.cssdoc" },
          "2": { name: TAG_SCOPE },
        },
        end: `(${BRACE_CLOSE.source})`,
        endCaptures: { "1": { name: "punctuation.definition.tag.end.cssdoc" } },
        patterns: [
          { match: PIPE.source, name: "punctuation.separator.cssdoc" },
          { match: `[^${BRACE_CLOSE_CHAR}${PIPE_CHAR}]+`, name: "markup.underline.link.cssdoc" },
        ],
      },
      // A record's name (`@component button`) reads like a type name. Listed before the bare keyword
      // rule so it claims the tag and colours the identifier that follows.
      "record-tag": {
        // A dotted name (`menu.item`) is a qualified member name — highlight it as one unit, not just
        // the segment before the first dot.
        match: `(${AT.source}(?:${recordTags}))${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${buildQualifiedIdentifier()})?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "entity.name.type.cssdoc" },
        },
      },
      // Modifiers are spelled many ways (`-color-secondary`, `button--secondary`, `primary`); colour the
      // whole name, using the same scope as parts so a component's members read consistently.
      "modifier-tag": {
        match: `(${AT.source}(?:${modifierTags}))${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${buildModifierName()})?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "entity.other.attribute-name.part.cssdoc" },
        },
      },
      // `@cssstate :state(open)` / `@cssstate :disabled` — colour the state token like a custom property.
      "state-tag": {
        match: `(${AT.source}(?:cssstate))${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${buildStateValue()})?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "support.type.custom-property.cssdoc" },
        },
      },
      "part-tag": {
        match: `(${AT.source}(?:${partTags}))${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${buildClassSelector()})?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "entity.other.attribute-name.part.cssdoc" },
        },
      },
      "property-tag": {
        match: `(${AT.source}(?:${propertyTags}))${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${buildCustomProperty()})?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "support.type.custom-property.cssdoc" },
        },
      },
      // `@ref 1` / `@ref 1.` — numeric annotation reference index.
      "ref-tag": {
        match: `(${AT.source}(?:ref))${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${DIGIT.source}+${DOT.source}?)?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "constant.numeric.cssdoc" },
        },
      },
      "member-tag": {
        match: `(${AT.source}(?:memberOf|member))${WORD_BOUNDARY.source}(?:${SPACE_TAB.source}+(${ALPHANUMERIC_EXTENDED.source}+)(?:${SPACE_TAB.source}+(private)(?!${ALPHANUMERIC_EXTENDED.source}))?)?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "entity.name.type.cssdoc" },
          "3": { name: "storage.modifier.cssdoc" },
        },
      },
      "block-tag": {
        match: `(${AT.source}(?:${blockTags}))${WORD_BOUNDARY.source}`,
        name: TAG_SCOPE,
      },
      // The `@structure` body is nested CSS. We light up structure tags, nested @scope at-rules,
      // parts (class selectors), slot declarations, cardinality modifiers, and braces that show nesting.
      // The region runs to the next tag or the comment's end. Listed before `#block-tag` so it claims
      // `@structure` first.
      "structure-tag": {
        begin: `(${AT.source}structure)${WORD_BOUNDARY.source}`,
        beginCaptures: { "1": { name: TAG_SCOPE } },
        end: String.raw`(?=@)|(?=\*/)`,
        patterns: [
          {
            match: `(${CSSDOC_STRUCTURE_TAG.source})${WORD_BOUNDARY.source}${SPACE_TAB.source}*(${CSSDOC_COMPONENT_REF.source})?`,
            captures: {
              "1": { name: TAG_SCOPE },
              "2": { name: TAG_SCOPE },
            },
          },
          {
            match: `${AT.source}scope(?!${ALPHANUMERIC_EXTENDED.source})`,
            name: TAG_SCOPE,
          },
          {
            match: `\\bslot\\b`,
            name: "entity.other.attribute-name.part.cssdoc",
          },
          {
            match: `:[a-z]+|:max-\\d+`,
            name: "variable.other.modifier.cssdoc",
          },
          {
            match: TOKEN_CLASS_SELECTOR.source,
            name: "entity.other.attribute-name.part.cssdoc",
          },
          {
            match: `[${BRACE_OPEN_CHAR}${BRACE_CLOSE_CHAR}]`,
            name: "punctuation.section.structure.cssdoc",
          },
        ],
      },
      "custom-property": {
        match: `(?![\\w-])${DOUBLE_DASH.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*`,
        name: "support.type.custom-property.cssdoc",
      },
    },
  };
}

/**
 * Build an injection grammar that highlights cssdoc record-reference at-rules in source CSS, for
 * examples like `@component top-nav (--desktop-nav) {}`.
 */
export function buildAtRuleInjectionGrammar(): InjectionGrammar {
  const recordTags = alt(cssdocTagNamesByKind("record"));
  const nativeCssAtRules = alt([
    "charset",
    "color-profile",
    "container",
    "counter-style",
    "document",
    "font-face",
    "font-feature-values",
    "font-palette-values",
    "import",
    "keyframes",
    "layer",
    "media",
    "namespace",
    "page",
    "property",
    "scope",
    "starting-style",
    "supports",
    "view-transition",
  ]);
  return {
    $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    name: "cssdoc-at-rules",
    scopeName: "source.css.cssdoc.atrules",
    injectionSelector: "L:meta.at-rule.css, L:meta.at-rule.scss, L:meta.at-rule.less",
    patterns: [
      { include: "#record-ref-atrule" },
      { include: "#untyped-ref-atrule" },
      { include: "#custom-property" },
    ],
    repository: {
      // Typed record refs: @component nav, with optional :profile / (--profile).
      "record-ref-atrule": {
        match:
          `(${AT.source}(?:${recordTags}))${WORD_BOUNDARY.source}(?:${SPACE_TAB.source}+(${buildIdentifier()}))?` +
          `(?:${SPACE_TAB.source}+(?:${PAREN_OPEN.source}\\s*${DOUBLE_DASH.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*\\s*${PAREN_CLOSE.source}|${COLON.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*))?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "entity.name.type.cssdoc" },
          "3": { name: "support.type.custom-property.cssdoc" },
        },
      },
      // Untyped refs: @nav / @header, with optional profile marker. Excludes native CSS at-rules.
      "untyped-ref-atrule": {
        match:
          `(${AT.source}(?!(?:${nativeCssAtRules})${WORD_BOUNDARY.source})(?:${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*))` +
          `(?:${SPACE_TAB.source}+(?:${PAREN_OPEN.source}\\s*${DOUBLE_DASH.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*\\s*${PAREN_CLOSE.source}|${COLON.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*))?`,
        captures: {
          "1": { name: TAG_SCOPE },
          "2": { name: "support.type.custom-property.cssdoc" },
        },
      },
      "custom-property": {
        match: `(?![\\w-])${DOUBLE_DASH.source}${ALPHA.source}${ALPHANUMERIC_EXTENDED.source}*`,
        name: "support.type.custom-property.cssdoc",
      },
    },
  };
}

/**
 * The host scopes the injection layers onto. It fires only where `comment.block.css` (etc.) appears —
 * see {@link InjectionGrammar.injectionSelector} — so listing the JS/HTML/Markdown/framework hosts is
 * safe: cssdoc lights up embedded CSS wherever another grammar embeds it, not just in `.css` files.
 */
export const injectTo: string[] = [
  "source.css",
  "source.scss",
  "source.less",
  "source.css.styled",
  "source.ts",
  "source.tsx",
  "source.js",
  "source.jsx",
  "source.vue",
  "source.svelte",
  "source.astro",
  "text.html.markdown",
  "text.html.basic",
  "text.html.derivative",
];

/** The cssdoc doc-comment injection grammar, shaped as a Shiki `LanguageRegistration`. */
export const cssdoc: InjectionLanguageRegistration = { ...buildInjectionGrammar(), injectTo };

/** The cssdoc record-ref at-rule injection grammar for source CSS. */
export const cssdocAtRules: InjectionLanguageRegistration = {
  ...buildAtRuleInjectionGrammar(),
  injectTo,
};

export default cssdoc;
