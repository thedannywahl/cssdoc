/**
 * @cssdoc/regex/scripts/generate-fixtures
 *
 * Autogenerates fixture files from PATTERN_DEFINITIONS.
 * Creates tier-based fixture files with comprehensive test cases.
 *
 * Usage: `vpx ./scripts/generate-fixtures.ts`
 */

import { PATTERN_DEFINITIONS } from "../src/definitions.js";
import { writeFileSync, mkdirSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Generate fixture file for a specific tier.
 */
function generateFixtureFile(tier: 0 | 1 | 2 | 3 | 4): string {
  const patterns = Object.entries(PATTERN_DEFINITIONS).filter(([, def]) => def.tier === tier);

  if (patterns.length === 0) {
    return "";
  }

  const header = `/**
 * @cssdoc/regex/fixtures/tier-${tier}.fixtures
 *
 * Autogenerated from definitions.ts
 * DO NOT EDIT MANUALLY — run \`vpx ./scripts/generate-fixtures.ts\` instead.
 *
 * Test fixtures for Tier ${tier} patterns.
 * Each pattern has positive and negative test cases.
 *
 * @module
 */

import { describe, it, expect } from "vite-plus/test";
import { PATTERN_DEFINITIONS } from "../src/definitions.js";

describe(\`Tier ${tier} Pattern Fixtures\`, () => {`;

  const tests = patterns
    .map(([name, def]) => {
      const { passes, fails } = def.fixtures;

      const passTests = passes
        .map((testCase: { input: string; note?: string }) => {
          const note = testCase.note ? ` - ${testCase.note}` : "";
          return `    it(\`matches \\"\${JSON.stringify(${JSON.stringify(testCase.input)})}\\"${note}\`, () => {
      const def = PATTERN_DEFINITIONS["${name}"];
      expect(def).toBeDefined();
      const regex = new RegExp(def.pattern as string);
      expect(regex.test(${JSON.stringify(testCase.input)})).toBe(true);
    });`;
        })
        .join("\n");

      const failTests = fails
        .map((testCase: { input: string; reason: string }) => {
          return `    it(\`rejects \\"\${JSON.stringify(${JSON.stringify(testCase.input)})}\\" - ${testCase.reason}\`, () => {
      const def = PATTERN_DEFINITIONS["${name}"];
      expect(def).toBeDefined();
      const regex = new RegExp(def.pattern as string);
      expect(regex.test(${JSON.stringify(testCase.input)})).toBe(false);
    });`;
        })
        .join("\n");

      return `  describe("${name}", () => {
${passTests}
${failTests}
  });`;
    })
    .join("\n");

  const footer = `
});
`;

  return header + "\n" + tests + footer;
}

// Generate and write fixture files
const fixturesDir = path.join(__dirname, "../fixtures");
mkdirSync(fixturesDir, { recursive: true });

for (const tier of [0, 1, 2, 3, 4] as const) {
  const content = generateFixtureFile(tier);
  if (content) {
    const outputPath = path.join(fixturesDir, `tier-${tier}.fixtures.ts`);
    writeFileSync(outputPath, content, "utf8");
    console.log(`✓ Generated ${outputPath}`);
  }
}
