/**
 * @cssdoc/regex/scripts/generate-index
 *
 * Autogenerates index.ts from PATTERN_DEFINITIONS.
 * Exports individual pattern objects with lazy resolution.
 *
 * Usage: `vpx ./scripts/generate-index.ts`
 */

import { PATTERN_DEFINITIONS } from "../src/definitions.js";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Generate index.ts with all pattern exports.
 */
function generateIndex(): string {
  const header = `/**
 * @cssdoc/regex
 *
 * Autogenerated from definitions.ts
 * DO NOT EDIT MANUALLY — run \`vpx ./scripts/generate-index.ts\` instead.
 *
 * Pattern exports with lazy resolution and composition support.
 *
 * @module
 */

import { PATTERN_DEFINITIONS } from "./definitions.js";

// Cache for resolved patterns
const patternCache = new Map<string, string>();

/**
 * Resolve a pattern by name, recursively resolving compositions.
 */
function resolvePattern(name: string): string {
  if (patternCache.has(name)) {
    return patternCache.get(name)!;
  }

  const def = PATTERN_DEFINITIONS[name];
  if (!def) {
    throw new Error(\`Pattern not found: \${name}\`);
  }

  let resolved: string;

  if (typeof def.pattern === "string") {
    resolved = def.pattern;
  } else if (typeof def.pattern === "function") {
    // Create resolver for composition
    const resolve = (depName: string) => resolvePattern(depName);
    resolved = def.pattern(resolve);
  } else {
    throw new Error(\`Invalid pattern type for \${name}\`);
  }

  patternCache.set(name, resolved);
  return resolved;
}

/**
 * Individual pattern exports for backward compatibility and convenience.
 * Each pattern is lazy-resolved on first access.
 */
`;

  // Sort by tier and name for consistent output
  const sorted = Object.entries(PATTERN_DEFINITIONS)
    .sort(([a], [b]) => {
      const tierA = PATTERN_DEFINITIONS[a].tier;
      const tierB = PATTERN_DEFINITIONS[b].tier;
      if (tierA !== tierB) return tierA - tierB;
      return a.localeCompare(b);
    })
    .map(([name]) => {
      const def = PATTERN_DEFINITIONS[name];

      return `/**
 * ${def.description}
 * @tier ${def.tier}
 */
export const ${name} = new RegExp(resolvePattern("${name}"), "${def.flags || ""}");
`;
    })
    .join("\n");

  const footer = `
// Re-export definitions for direct access
export { PATTERN_DEFINITIONS } from "./definitions.js";
export type { UnifiedPatternDef } from "./definitions.js";
export { PATTERNS } from "./patterns.js";
export type * from "./types.js";
`;

  return header + "\n" + sorted + footer;
}

// Generate and write
const output = generateIndex();
const outputPath = path.join(__dirname, "../src/index.ts");

writeFileSync(outputPath, output, "utf8");
console.log(`✓ Generated ${outputPath}`);
console.log(`  Pattern exports: ${Object.keys(PATTERN_DEFINITIONS).length}`);
