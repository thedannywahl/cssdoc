/**
 * @cssdoc/regex/scripts/generate-patterns
 *
 * Autogenerates patterns.ts from PATTERN_DEFINITIONS.
 * This script reads definitions.ts, resolves all pattern compositions,
 * and outputs patterns.ts with the same structure as before.
 *
 * Usage: `vpx ./scripts/generate-patterns.ts`
 */

import type { UnifiedPatternDef } from "../src/definitions.js";
import { PATTERN_DEFINITIONS } from "../src/definitions.js";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Resolve a single pattern definition, recursively resolving compositions.
 */
function resolvePattern(
  name: string,
  definitions: Record<string, UnifiedPatternDef>,
  cache: Map<string, string> = new Map(),
): string {
  if (cache.has(name)) {
    return cache.get(name)!;
  }

  const def = definitions[name];
  if (!def) {
    throw new Error(`Pattern not found: ${name}`);
  }

  let resolved: string;

  if (typeof def.pattern === "string") {
    resolved = def.pattern;
  } else if (typeof def.pattern === "function") {
    // Create resolver for composition
    const resolve = (depName: string) => resolvePattern(depName, definitions, cache);
    resolved = def.pattern(resolve);
  } else {
    throw new Error(`Invalid pattern type for ${name}`);
  }

  cache.set(name, resolved);
  return resolved;
}

/**
 * Generate patterns.ts with all resolved patterns.
 */
function generatePatterns(): string {
  const header = `/**
 * @cssdoc/regex/patterns
 *
 * Autogenerated from definitions.ts
 * DO NOT EDIT MANUALLY — run \`vpx ./scripts/generate-patterns.ts\` instead.
 *
 * @module
 */

/**
 * Resolved patterns with metadata and types.
 * Key = pattern name, value = pattern object with source string and types.
 */
export const PATTERNS = {`;

  const resolutionCache = new Map<string, string>();

  // Sort by tier and name for consistent output
  const sorted = Object.entries(PATTERN_DEFINITIONS).sort(([a], [b]) => {
    const tierA = PATTERN_DEFINITIONS[a].tier;
    const tierB = PATTERN_DEFINITIONS[b].tier;
    if (tierA !== tierB) return tierA - tierB;
    return a.localeCompare(b);
  });

  const patterns = sorted
    .map(([name, def]) => {
      const resolved = resolvePattern(name, PATTERN_DEFINITIONS, resolutionCache);

      // Format captures if present
      let capturesComment = "";
      if (def.captures && Object.keys(def.captures).length > 0) {
        const captureLines = Object.entries(def.captures)
          .map(([key, desc]) => `   *   ${key}: ${desc}`)
          .join("\n");
        capturesComment = `\n   * Captures:\n${captureLines}`;
      }

      // Format description
      const description = def.description;
      const composedNote = def.composedFrom
        ? ` (composed from: ${def.composedFrom.join(", ")})`
        : "";

      return `  /**
   * ${description}${composedNote}
   * @tier ${def.tier}${capturesComment}
   */
  ${name}: {
    source: ${JSON.stringify(resolved)},
    tier: ${def.tier},
    description: ${JSON.stringify(description)},
  },`;
    })
    .join("\n");

  const footer = `
};
`;

  return header + "\n" + patterns + footer;
}

// Generate and write
const output = generatePatterns();
const outputPath = path.join(__dirname, "../src/patterns.ts");

writeFileSync(outputPath, output, "utf8");
console.log(`✓ Generated ${outputPath}`);
console.log(`  Patterns exported: ${Object.keys(PATTERN_DEFINITIONS).length}`);
