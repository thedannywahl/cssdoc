/**
 * @cssdoc/regex/scripts/generate-types
 *
 * Autogenerates types.ts from PATTERN_DEFINITIONS.
 * Exports TypeScript types for all capture groups and pattern records.
 *
 * Usage: `vpx ./scripts/generate-types.ts`
 */

import { PATTERN_DEFINITIONS } from "../src/definitions.js";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Generate types.ts with all capture group types.
 */
function generateTypes(): string {
  const header = `/**
 * @cssdoc/regex/types
 *
 * Autogenerated from definitions.ts
 * DO NOT EDIT MANUALLY — run \`vpx ./scripts/generate-types.ts\` instead.
 *
 * TypeScript types for pattern capture groups.
 *
 * @module
 */

`;

  // Generate capture group types for patterns that have them
  const captureTypes = Object.entries(PATTERN_DEFINITIONS)
    .filter(([, def]) => def.captures && Object.keys(def.captures).length > 0)
    .map(([name, def]) => {
      const typeName = `${name}Captures`;
      const captures = def.captures!;
      const fields = Object.entries(captures)
        .map(([key, desc]) => `  /** ${desc} */\n  ${key}?: string;`)
        .join("\n");

      return `/**
 * Capture groups for pattern \`${name}\`
 * @see ${name}
 */
export interface ${typeName} {
${fields}
}
`;
    })
    .join("\n");

  // Generate pattern record type
  const patternRecordType = `/**
 * All available patterns with their source strings and metadata.
 */
export type PatternsRecord = Record<string, {
  source: string;
  tier: 0 | 1 | 2 | 3 | 4;
  description: string;
}>;

export declare const PATTERNS: PatternsRecord;
`;

  return header + captureTypes + "\n" + patternRecordType;
}

// Generate and write
const output = generateTypes();
const outputPath = path.join(__dirname, "../src/types.ts");

writeFileSync(outputPath, output, "utf8");
console.log(`✓ Generated ${outputPath}`);

// Count types generated
const typeCount = Object.entries(PATTERN_DEFINITIONS).filter(
  ([, def]) => def.captures && Object.keys(def.captures).length > 0,
).length;
console.log(`  Capture group types: ${typeCount}`);
